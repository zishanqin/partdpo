(() => {
  'use strict';
  const root = document.querySelector('#gallery-grid');
  if (!root) return;
  const reduce = matchMedia('(prefers-reduced-motion: reduce)');
  const pause = document.querySelector('#gallery-pause');
  const dialog = document.querySelector('#parts-dialog');
  const partsGrid = document.querySelector('#parts-grid');
  const partsMotion = document.querySelector('#parts-motion');
  let paused = reduce.matches;
  let partsPaused = reduce.matches;
  let speed = 36;
  let modalOpener = null;
  let modalViews = [];
  const galleryViews = [];
  const visible = new WeakMap();
  const observer = new IntersectionObserver(entries => {
    for (const entry of entries) {
      visible.set(entry.target, entry.isIntersecting);
      const view = [...galleryViews, ...modalViews].find(v => v.el === entry.target);
      if (view) view.update();
    }
  }, {threshold:0.02});

  const element = (tag, cls, text) => {
    const el = document.createElement(tag);
    if (cls) el.className = cls;
    if (text) el.textContent = text;
    return el;
  };
  const button = (text, label) => {
    const el = element('button', 'small-control', text);
    el.type = 'button';
    if (label) { el.setAttribute('aria-label', label); el.title = label; }
    return el;
  };

  function viewport({name, src, part = false, radius = null, magnification = 1}) {
    const el = element('div', 'model-view');
    const mv = element('model-viewer');
    mv.setAttribute('alt', `${name}, generated by PartDPO`);
    mv.setAttribute('src', src);
    mv.setAttribute('loading', 'eager');
    mv.setAttribute('reveal', 'auto');
    mv.setAttribute('environment-image', 'neutral');
    mv.setAttribute('exposure', '1');
    mv.setAttribute('shadow-intensity', part ? '0' : '0.45');
    mv.setAttribute('shadow-softness', '1');
    mv.setAttribute('interaction-prompt', 'none');
    mv.setAttribute('disable-pan', '');
    mv.setAttribute('touch-action', 'pan-y');
    mv.setAttribute('auto-rotate-delay', '0');
    mv.setAttribute('rotation-per-second', `${speed}deg`);
    mv.setAttribute('interpolation-decay', '80');
    const orbit = radius ? `25deg 70deg ${radius / magnification}m` : '25deg 70deg auto';
    mv.setAttribute('camera-orbit', orbit);
    if (part) {
      mv.setAttribute('camera-target', '0m 0m 0m');
      mv.setAttribute('field-of-view', '30deg');
      // Fixed radius preserves relative part sizes; tiny-part magnification is labelled.
      mv.setAttribute('min-camera-orbit', 'auto auto 0.02m');
      mv.setAttribute('max-camera-orbit', 'auto auto 20m');
    }
    const loading = element('p', 'model-loading', 'Loading 3D…');
    loading.setAttribute('role','status');
    el.append(mv, loading);
    const inter = button('Interact', `Interact with ${name}`);
    inter.setAttribute('aria-pressed','false');
    let interactive = false;
    let failed = false;
    const update = () => {
      const stopped = part ? partsPaused : paused;
      const behindModal = !part && dialog.open;
      const spin = !interactive && !stopped && !failed && !document.hidden && !behindModal && visible.get(el) !== false;
      mv.toggleAttribute('auto-rotate', spin);
      mv.toggleAttribute('camera-controls', interactive);
      inter.textContent = interactive ? 'Auto rotate' : 'Interact';
      inter.setAttribute('aria-label', `${interactive ? 'Auto rotate' : 'Interact with'} ${name}`);
      inter.title = interactive ? 'Resume automatic rotation' : 'Drag to rotate; scroll or pinch to zoom';
      inter.setAttribute('aria-pressed', String(interactive));
      el.dataset.mode = interactive ? 'interactive' : spin ? 'rotating' : 'paused';
    };
    inter.addEventListener('click', () => { interactive = !interactive; update(); });
    mv.addEventListener('load', () => { loading.hidden = true; el.dataset.ready = 'true'; update(); });
    mv.addEventListener('error', () => {
      failed = true; loading.hidden = false; loading.textContent = '3D unavailable. See the paper comparisons below.'; inter.disabled = true; el.dataset.ready = 'error'; update();
    });
    const reset = () => {
      mv.setAttribute('camera-orbit', orbit);
      mv.setAttribute('field-of-view', part ? '30deg' : 'auto');
      mv.resetTurntableRotation(0);
      mv.jumpCameraToGoal();
    };
    observer.observe(el);
    update();
    return {el, mv, inter, update, reset, dispose:() => observer.unobserve(el)};
  }

  function updateMotion() {
    pause.textContent = paused ? 'Resume rotation' : 'Pause all';
    pause.setAttribute('aria-pressed',String(paused));
    partsMotion.textContent = partsPaused ? 'Resume rotation' : 'Pause rotation';
    partsMotion.setAttribute('aria-pressed',String(partsPaused));
    [...galleryViews, ...modalViews].forEach(v => v.update());
  }
  pause.addEventListener('click', () => { paused = !paused; updateMotion(); });
  partsMotion.addEventListener('click', () => { partsPaused = !partsPaused; updateMotion(); });
  document.addEventListener('visibilitychange', updateMotion);
  reduce.addEventListener('change', e => { if (e.matches) { paused = true; partsPaused = true; updateMotion(); } });

  function openParts(obj, opener) {
    modalOpener = opener;
    partsGrid.replaceChildren();
    modalViews.forEach(v => v.dispose());
    modalViews = [];
    partsPaused = reduce.matches;
    document.querySelector('#parts-dialog-title').textContent = `${obj.name} · ${obj.parts} parts`;
    const reference = element('figure','part-cell assembled-reference');
    const refView = viewport({name:`${obj.name}, assembled reference`,src:obj.model,part:true});
    reference.append(element('figcaption','','Assembled reference'),refView.el,refView.inter);
    partsGrid.append(reference); modalViews.push(refView);
    for (const p of obj.partModels) {
      const cell = element('figure', 'part-cell');
      const caption = element('figcaption');
      const colour = element('span','part-colour');
      colour.style.backgroundColor = `rgb(${p.colour.map(c=>Math.round(c*255)).join(',')})`;
      colour.setAttribute('aria-hidden','true');
      caption.append(colour,document.createTextNode(p.label));
      let mag=1;
      while(p.extent * mag < obj.partScale * 0.22 && mag < 16) mag *= 2;
      if (mag > 1) {
        const scale = element('span','part-scale',`×${mag}`);
        scale.title = `Enlarged ${mag}× relative to the shared part scale`;
        scale.setAttribute('aria-label', scale.title);
        caption.append(scale);
      }
      const view = viewport({name:`${obj.name}, ${p.label}`,src:p.model,part:true,radius:obj.partScale*2.8,magnification:mag});
      cell.append(caption,view.el,view.inter);
      partsGrid.append(cell); modalViews.push(view);
    }
    dialog.showModal();
    document.body.classList.add('parts-open');
    updateMotion();
  }
  document.querySelector('#close-parts').addEventListener('click', () => dialog.close());
  dialog.addEventListener('close', () => {
    modalViews.forEach(v=>v.dispose());modalViews=[];partsGrid.replaceChildren();
    document.body.classList.remove('parts-open');updateMotion();modalOpener?.focus();
  });
  dialog.addEventListener('click', e => {
    if(e.target!==dialog)return;
    const r=dialog.getBoundingClientRect();
    if(e.clientX<r.left||e.clientX>r.right||e.clientY<r.top||e.clientY>r.bottom)dialog.close();
  });

  async function init() {
    const response = await fetch('assets/models/gallery.json');
    if(!response.ok)throw new Error('Gallery manifest unavailable');
    const data = await response.json();
    if(!data.objects?.length)throw new Error('No models');
    speed = data.rotationDegreesPerSecond;
    await loadModelViewer();
    root.replaceChildren();
    for(const obj of data.objects) {
      const card=element('article','gallery-card');card.dataset.object=obj.id;
      const heading=element('div','gallery-card-heading');
      heading.append(element('h3','',obj.name),element('span','',`${obj.parts} parts`));
      const stage=element('div','gallery-stage');
      const input=element('figure','gallery-input');
      const img=element('img');img.src=obj.input;img.alt=`Input image: ${obj.name}`;img.width=90;img.height=120;
      input.append(img,element('figcaption','','Input'));
      const view=viewport({name:obj.name,src:obj.model});
      galleryViews.push(view);
      stage.append(input,view.el);
      const controls=element('div','gallery-controls');
      const parts=button('Parts',`Explore parts of ${obj.name}`);
      parts.addEventListener('click',()=>openParts(obj,parts));
      const reset=button('Reset',`Reset view of ${obj.name}`);reset.addEventListener('click',view.reset);
      controls.append(view.inter,parts,reset);
      card.append(heading,stage,controls);root.append(card);
    }
    pause.hidden=false;updateMotion();
  }
  init().catch(() => {
    root.replaceChildren(element('p','gallery-error','The 3D gallery could not load. Original paper comparisons are available in Results below.'));
  });
})();
